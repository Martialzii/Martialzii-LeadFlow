import json
from datetime import datetime
from typing import Dict, List

class FutureMarketEngine:
    """Orchestrates future-generation marketing intelligence"""
    
    def __init__(self):
        self.version = "1.1.0-extension"
        self.generations = {
            "gen_alpha": {"birth_years": "2010-2025", "platforms": ["Roblox", "YouTube", "Minecraft"]},
            "gen_beta": {"birth_years": "2025-2040", "platforms": ["AI-native", "Metaverse", "AR/VR"]}
        }
        self.load_profiles()
    
    def load_profiles(self):
        """Load Gen Alpha behavioral profiles"""
        try:
            with open('extension/gen_alpha_profiles.json', 'r') as f:
                self.profiles = json.load(f)
        except FileNotFoundError:
            self.profiles = self._create_default_profiles()
    
    def _create_default_profiles(self):
        """Default profiles if JSON doesn't exist"""
        return {
            "gaming_enthusiast": {
                "primary_platform": "Roblox",
                "content_preference": "interactive stories",
                "purchase_influence": "high",
                "trust_signals": ["creators", "friends", "gameplay"]
            },
            "video_native": {
                "primary_platform": "YouTube",
                "content_preference": "shorts & challenges",
                "purchase_influence": "medium",
                "trust_signals": ["creators", "humor", "authenticity"]
            }
        }
    
    def analyze_trend(self, trend_data: Dict) -> Dict:
        """
        Analyze a trend for future market potential
        
        Args:
            trend_data: {'keyword': str, 'platform': str, 'velocity': int}
        
        Returns:
            Enriched trend with generation targeting
        """
        platform = trend_data.get('platform', '').lower()
        
        # Determine which generation this trend belongs to
        generation = "gen_alpha"
        if platform in ["roblox", "minecraft", "youtube"]:
            generation = "gen_alpha"
        elif platform in ["metaverse", "ar", "vr", "ai"]:
            generation = "gen_beta"
        
        # Find matching profile
        matched_profile = None
        for profile_name, profile_data in self.profiles.items():
            if profile_data.get('primary_platform', '').lower() in platform:
                matched_profile = profile_name
                break
        
        return {
            "original_trend": trend_data,
            "target_generation": generation,
            "matched_profile": matched_profile or "general",
            "campaign_angle": self._generate_angle(trend_data, generation),
            "timestamp": datetime.now().isoformat()
        }
    
    def _generate_angle(self, trend_data: Dict, generation: str) -> str:
        """Generate campaign angle based on generation"""
        angles = {
            "gen_alpha": f"Gamify this: {trend_data.get('keyword')} as a Roblox quest",
            "gen_beta": f"AI-personalize: {trend_data.get('keyword')} for immersive AR"
        }
        return angles.get(generation, f"Engage with: {trend_data.get('keyword')}")
    
    def export_to_github_issue(self, analyzed_trend: Dict) -> str:
        """Format for GitHub Project issue creation"""
        return f"""
        ## [FUTURE MARKET] {analyzed_trend['target_generation'].upper()} Trend: {analyzed_trend['original_trend']['keyword']}
        
        **Platform:** {analyzed_trend['original_trend']['platform']}
        **Generation:** {analyzed_trend['target_generation']}
        **Profile:** {analyzed_trend['matched_profile']}
        
        **Campaign Angle:**
        {analyzed_trend['campaign_angle']}
        
        **Actions:**
        - [ ] Validate with {analyzed_trend['target_generation']} persona
        - [ ] Create platform-specific content
        - [ ] Deploy to {analyzed_trend['original_trend']['platform']}
        - [ ] Measure engagement (48-hour window)
        
        ---
        *Generated by LeadFlow-X Extension v1.1.0*
        """

# Integration with your existing LeadFlow
def integrate_with_leadflow(leadflow_instance):
    """Bridge between existing LeadFlow and new Future Engine"""
    future_engine = FutureMarketEngine()
    
    # Monkey-patch or extend your existing leadflow methods
    if hasattr(leadflow_instance, 'process_lead'):
        original_process = leadflow_instance.process_lead
        
        def enhanced_process(lead_data):
            # Check if this is a future-market lead
            if 'platform' in lead_data and lead_data['platform'].lower() in ['roblox', 'youtube', 'minecraft']:
                future_insight = future_engine.analyze_trend(lead_data)
                lead_data['future_insight'] = future_insight
                lead_data['generation'] = future_insight['target_generation']
            
            return original_process(lead_data)
        
        leadflow_instance.process_lead = enhanced_process
    
    return leadflow_instance

